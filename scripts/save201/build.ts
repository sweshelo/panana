// Rebuild the checked-in ARM words. Requires devkitARM; never reads a ROM or save.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dir, '../..');
const toolchain = (process.env.DEVKITARM ?? (process.platform === 'win32' ? 'C:/devkitPro/devkitARM' : '/opt/devkitpro/devkitARM'))
  .replace(process.platform === 'win32' ? /^\/opt\/devkitpro\// : /$^/, 'C:/devkitPro/');
const dir = join(root, 'roms/save201');
mkdirSync(dir, { recursive: true });
const inputs = ['runtime.c', 'bridges.S', 'runtime.ld'].map(n => join(import.meta.dir, n));
const sourceHash = createHash('sha256').update(inputs.map(p => readFileSync(p, 'utf8').replaceAll('\r\n', '\n')).join('\n')).digest('hex');
const elf = join(dir, 'runtime.elf');
const result = Bun.spawnSync([
  join(toolchain, 'bin/arm-none-eabi-gcc' + (process.platform === 'win32' ? '.exe' : '')),
  '-Os', '-marm', '-march=armv6k', '-ffreestanding', '-fno-builtin', '-fno-unwind-tables',
  '-fno-asynchronous-unwind-tables', '-fno-stack-protector', '-fno-strict-aliasing', '-nostdlib',
  '-Wl,--emit-relocs', `-Wl,-T,${inputs[2]}`, inputs[0]!, inputs[1]!, '-o', elf,
], { cwd: root, env: { ...process.env, SOURCE_DATE_EPOCH: '0' }, stdout: 'pipe', stderr: 'pipe' });
if (result.exitCode) throw new Error(new TextDecoder().decode(result.stderr));
const b = readFileSync(elf);
if (b.readUInt32LE(0) !== 0x464c457f || b[4] !== 1 || b[5] !== 1 || b.readUInt16LE(18) !== 40) throw new Error('Expected ELF32 little-endian ARM');
const sh = b.readUInt32LE(32), stride = b.readUInt16LE(46);
const sections = Array.from({ length: b.readUInt16LE(48) }, (_, i) => {
  const p = sh + i * stride;
  return { type: b.readUInt32LE(p + 4), offset: b.readUInt32LE(p + 16), size: b.readUInt32LE(p + 20), link: b.readUInt32LE(p + 24), info: b.readUInt32LE(p + 28), entry: b.readUInt32LE(p + 36) };
});
const payload = sections[1]!;
const code = b.subarray(payload.offset, payload.offset + payload.size);
if (code.length % 4 || code.length > 0xf60) throw new Error(`ARM runtime does not fit cave: ${code.length} bytes`);
const symbols: Record<string, number> = {};
for (const s of sections.filter(s => s.type === 2)) {
  const strings = sections[s.link]!;
  for (let p = s.offset; p < s.offset + s.size; p += s.entry) {
    if (b.readUInt16LE(p + 14) !== 1) continue;
    const n = strings.offset + b.readUInt32LE(p);
    const name = b.subarray(n, b.indexOf(0, n)).toString('utf8');
    if (name && !name.startsWith('$') && name !== '.payload') symbols[name] = b.readUInt32LE(p + 4);
  }
}
const relocations: number[] = [];
for (const s of sections.filter(s => s.type === 9 && s.info === 1)) {
  for (let p = s.offset; p < s.offset + s.size; p += s.entry) {
    const type = b.readUInt32LE(p + 4) & 255;
    if (type === 2) relocations.push(b.readUInt32LE(p));
    else if (type !== 28 && type !== 29) throw new Error(`Unsupported ARM relocation ${type}`);
  }
}
const words = Array.from({ length: code.length / 4 }, (_, i) => `0x${code.readUInt32LE(i * 4).toString(16).padStart(8, '0')}`);
const text = `// Generated by scripts/save201/build.ts from our freestanding sources; contains no ROM bytes.\n`
  + `export const SAVE201_SOURCE_HASH = '${sourceHash}';\n`
  + `export const SAVE201_WORDS = [\n${Array.from({ length: Math.ceil(words.length / 8) }, (_, i) => '  ' + words.slice(i * 8, i * 8 + 8).join(', ') + ',').join('\n')}\n];\n`
  + `export const SAVE201_RELOCATIONS = ${JSON.stringify(relocations)};\n`
  + `export const SAVE201_SYMBOLS: Record<string, number> = ${JSON.stringify(symbols, null, 2)};\n`;
writeFileSync(join(root, 'src/game/savepatchdata.ts'), text);
console.log(`save201: ${code.length} bytes, ${relocations.length} absolute relocations, source ${sourceHash}`);
